// Generates docs/GP-FORMULA-INVENTORY.md from the Airtable Meta API.
//
// This is the capture the unify-estimates bet requires BEFORE anything Airtable-side
// is retired: "capture the full formula text of all three families (plus their
// upstream rollups and each rollup's Status filter)".
//
// It turns out only HALF of that is possible from the API — see the generated doc.
// Re-run whenever the Airtable schema changes; the manual TODOs must be re-checked.
//
// Usage:  node db/etl/gp-inventory.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = process.env.REPO_ROOT || path.resolve(HERE, "..", "..");
const env = Object.fromEntries(
  fs.readFileSync(path.join(ROOT, ".env"), "utf8")
    .split(/\r?\n/).filter(l => l && !l.startsWith("#") && l.includes("="))
    .map(l => [l.slice(0, l.indexOf("=")).trim(), l.slice(l.indexOf("=") + 1).trim()])
);

const BASE = "appiqWg6SvKcGfMAu";
const r = await fetch(`https://api.airtable.com/v0/meta/bases/${BASE}/tables`, {
  headers: { Authorization: `Bearer ${env.AIRTABLE_PROD_READ_PAT}` },
});
if (!r.ok) throw new Error(`meta ${r.status}: ${(await r.text()).slice(0, 200)}`);
const schema = await r.json();

const nameById = new Map();
for (const t of schema.tables) for (const f of t.fields) nameById.set(f.id, f.name);
const resolve = s => String(s || "")
  .replace(/\{(fld[A-Za-z0-9]{14})\}/g, (m, id) => "{" + (nameById.get(id) || id) + "}")
  .replace(/\s+/g, " ").trim();

const jobs = schema.tables.find(t => t.name === "Jobs");
const MONEY = /gross profit|revenue|cost|unbilled|billed|profit|markup|contract|material|labor|hours/i;
const formulas = jobs.fields.filter(f => f.type === "formula" && MONEY.test(f.name));
const rollups  = jobs.fields.filter(f => f.type === "rollup"  && MONEY.test(f.name));

const allRollups = schema.tables.flatMap(t => t.fields.filter(f => f.type === "rollup"));
const fence = "```";
const L = [];

L.push("# GP / financial field inventory — Airtable Jobs table");
L.push("");
L.push("Generated by `db/etl/gp-inventory.mjs` from the Airtable Meta API. Re-run it when");
L.push("the schema changes. **The manual TODOs below must be re-checked when you do.**");
L.push("");
L.push("This is the capture the unify-estimates bet requires *before* anything");
L.push("Airtable-side is retired.");
L.push("");
L.push("## ⚠ What the API cannot tell us");
L.push("");
L.push(`This base has **${allRollups.length} rollup fields**. For every single one the Meta API`);
L.push("returns only `recordLinkFieldId`, `fieldIdInLinkedTable`, `referencedFieldIds` and");
L.push("`result`. It does **not** expose the aggregation function (sum / max / AND …), and it");
L.push("does **not** expose the condition deciding which linked records are counted.");
L.push("");
L.push("Proof: `Expected Revenue` and `Expected Revenue (All Status)` return **byte-identical**");
L.push("options — same link field, same target field, same result type — yet produce different");
L.push("numbers. Same for `Actual Labor Cost (Reviewed)` vs `Labor Cost (In Progress)`.");
L.push("");
L.push("**Consequence for the Neon port:** the rollups below cannot be reproduced from the API");
L.push("alone. Each needs its aggregation and filter read off the Airtable UI by hand, or");
L.push("inferred by comparing its value against the underlying linked records across many");
L.push("jobs. Formula fields, by contrast, are fully recoverable and appear verbatim below.");
L.push("");
L.push("This is also *why* CLAUDE.md warns that the FILTERED vs UNFILTERED rollup naming is");
L.push("deliberately counterintuitive — there is nothing in the schema to check a guess against.");
L.push("");
L.push(`## Formula fields — RECOVERABLE (${formulas.length})`);
L.push("");
L.push("Verbatim, with field IDs resolved to names.");
for (const f of formulas) {
  L.push("");
  L.push("### " + f.name);
  L.push(fence);
  L.push(resolve(f.options?.formula));
  L.push(fence);
}
L.push("");
L.push(`## Rollup fields — INCOMPLETE (${rollups.length})`);
L.push("");
L.push("Aggregation and filter **must be captured manually**. Until every TODO here is filled");
L.push("in and each ported view diffed job-by-job against Airtable, nothing Airtable-side may");
L.push("be retired.");
L.push("");
L.push("| Field | Linked via | Rolls up | Aggregation | Filter |");
L.push("|---|---|---|---|---|");
for (const f of rollups) {
  const o = f.options || {};
  L.push(`| ${f.name} | ${nameById.get(o.recordLinkFieldId) || "?"} | ` +
         `${nameById.get(o.fieldIdInLinkedTable) || "?"} | **TODO** | **TODO** |`);
}
L.push("");
L.push("## Billing / allocation tables these depend on");
L.push("");
L.push("Scoped 2026-07-31: **six** tables, not the two the plan originally assumed.");
L.push("");
L.push("| Table | id | fields |");
L.push("|---|---|---|");
for (const t of schema.tables) {
  if (/labor|alloc/i.test(t.name)) L.push(`| ${t.name} | \`${t.id}\` | ${t.fields.length} |`);
}
L.push("");

fs.writeFileSync(path.join(ROOT, "docs/GP-FORMULA-INVENTORY.md"), L.join("\n"));
console.log(`wrote docs/GP-FORMULA-INVENTORY.md`);
console.log(`  formulas captured verbatim : ${formulas.length}`);
console.log(`  rollups needing manual work : ${rollups.length}`);
console.log(`  rollups base-wide           : ${allRollups.length} (none expose aggregation or filter)`);
